// lucide-react 1.x dropped its brand logos, so these stand in for the ones the
// site uses. They take the same props as a lucide icon (size, className, ...).
import type { SVGProps } from 'react';
import type { LucideIcon } from 'lucide-react';

type IconProps = Omit<SVGProps<SVGSVGElement>, 'ref'> & { size?: number | string };

function icon(children: React.ReactNode): LucideIcon {
  const BrandIcon = ({ size = 24, strokeWidth = 2, ...props }: IconProps) => (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
  return BrandIcon as unknown as LucideIcon;
}

